    private void jButtonAdicionaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAdicionaActionPerformed
        String nome = jTextFieldNome.getText();
        String login = jTextFieldLogin.getText();
        String senha = jTextFieldSenha.getText();
        GerenciamentoJogador genJog = GerenciamentoJogador.getInstance();
        if (genJog.validarLogin(login)){
            JOptionPane.showMessageDialog(rootPane, "Login utilizado \nTente outro login!");
        }else {
            genJog.adicionarJogador(nome, login, senha);
            System.out.println(genJog.listarJogadores());
            JOptionPane.showMessageDialog(rootPane, "Jogador adicionado com sucesso!");
            this.setVisible(false);
        }

    }//GEN-LAST:event_jButtonAdicionaActionPerformed

